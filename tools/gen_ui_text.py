# -*- coding: utf-8 -*-
r"""
Emit STM32F407_ProjectTemplate\bsp\ui\ui_text.h - the UI label table.

The labels are written as octal-escaped UTF-8 string literals so the C source
stays pure ASCII (Keil/ARMCC then needs no UTF-8 locale, and there is no
"non-ASCII character in source" surprise on the user's machine).

Edit LABELS below and re-run:
    python tools/gen_ui_text.py
Every CJK character used here must also be present in the font, i.e. listed in
tools/gen_ui_font.py's CJK string (re-run that one first if you add a new one).
"""

import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "STM32F407_ProjectTemplate", "bsp", "ui", "ui_text.h")
FONT = os.path.join(ROOT, "STM32F407_ProjectTemplate", "bsp", "ui", "ui_font_cn14.h")

LABELS = [
    ("TITLE",    "双核示波器",  "product name"),
    ("TIMEBASE", "时基",        "time/div"),
    ("VDIV",     "电压",        "volts/div"),
    ("SRATE",    "采样",        "sample rate"),
    ("RUN",      "运行",        "running"),
    ("STOP",     "停止",        "stopped"),
    ("CH1",      "通道1",       "channel 1"),
    ("CH2",      "通道2",       "channel 2"),
    ("MENU",     "菜单",        "menu title"),
    ("EXIT",     "退出",        "exit"),
    ("ON",       "开",          "on"),
    ("OFF",      "关",          "off"),
    ("TRIG",     "触发",        "trigger enable"),
    ("EDGE",     "边沿",        "trigger edge"),
    ("RISE",     "上升",        "rising edge"),
    ("FALL",     "下降",        "falling edge"),
    ("LEV",      "电平",        "trigger level"),
    ("MODE",     "模式",        "trigger mode"),
    ("AUTO",     "自动",        "auto mode"),
    ("NORM",     "常态",        "normal mode"),
    ("SINGL",    "单次",        "single mode"),
    ("MEAS",     "测量",        "measurement"),
    ("VPP",      "峰峰",        "peak-to-peak"),
    ("VAVG",     "平均",        "average"),
    ("FREQ",     "频率",        "frequency"),
    ("DUTY",     "占空比",      "duty cycle"),
]


def c_literal(s):
    """octal-escaped UTF-8 (escape ends after exactly 3 digits -> never greedy)"""
    out = []
    for b in s.encode("utf-8"):
        if 0x20 <= b < 0x7F and chr(b) not in '"\\':
            out.append(chr(b))
        else:
            out.append("\\%03o" % b)
    return '"' + "".join(out) + '"'


# which unicode values the generated font actually carries
font_uni = set()
for m in re.finditer(r"\{0x([0-9A-F]{4}),", open(FONT, encoding="utf-8").read()):
    font_uni.add(int(m.group(1), 16))

missing = []
lines = []

for name, text, desc in LABELS:
    cps = " ".join("U+%04X" % ord(c) for c in text)
    for c in text:
        if ord(c) > 0x7F and ord(c) not in font_uni:
            missing.append((name, c))
    w = " " * max(0, 11 - len(name))
    lines.append('/* %s : %s  %s */' % (cps, desc, text.encode("unicode_escape").decode()))
    lines.append('#define S_%s%s %s' % (name, w, c_literal(text)))

with open(OUT, "w", encoding="utf-8", newline="\n") as f:
    f.write("/* Auto-generated by tools/gen_ui_text.py -- edit LABELS there. */\n")
    f.write("#ifndef UI_TEXT_H\n#define UI_TEXT_H\n\n")
    f.write("/* UTF-8 UI labels (octal escapes keep this file pure ASCII).\n")
    f.write(" * The first comment on each line lists the unicode codepoints. */\n\n")
    f.write("\n".join(lines))
    f.write("\n\n#endif /* UI_TEXT_H */\n")

if missing:
    print("MISSING from the font (%d):" % len(missing))
    for name, c in missing:
        print("   %s -> %s" % (name, c))
    sys.exit(1)

print("wrote %s (%d labels, all glyphs present)" % (OUT, len(LABELS)))
